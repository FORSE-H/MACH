#!/usr/bin/env python3
"""check_consistency.py — one source of truth for catalogue facts in prose.

The entries/ directory is ground truth: the number of entries and the number of
categories are computed from it. This script checks that the human-facing claims
in README.md and index.html match that truth, so the README can never silently
drift (e.g. "230+ entries" while the catalogue holds 241).

The claims live inside HTML-comment markers so they can be rewritten mechanically
and are invisible in rendered Markdown:

    README.md    <!-- MACH:ENTRY_COUNT -->241<!-- /MACH:ENTRY_COUNT -->
                 <!-- MACH:CATEGORY_COUNT -->8<!-- /MACH:CATEGORY_COUNT -->
    index.html   <!-- STAT:TOTAL -->241<!-- /STAT:TOTAL -->   (written by generate_entries.py)

Usage:
    python scripts/check_consistency.py            # verify; exit 1 on drift (CI gate)
    python scripts/check_consistency.py --check     # same, explicit
    python scripts/check_consistency.py --write      # rewrite the README markers to match

index.html's STAT markers are produced by generate_entries.py, so this script
only *checks* them (it does not rewrite index.html); if they drift, the fix is to
run generate_entries.py, which the check message says.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ENTRIES = Path("entries")
README = Path("README.md")
INDEX = Path("index.html")


def ground_truth() -> tuple[int, int]:
    """(entry_count, category_count) computed from entries/."""
    cats: set[str] = set()
    n = 0
    for f in sorted(ENTRIES.rglob("*.jsonld")):
        if f.name.startswith("_"):
            continue
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        n += 1
        c = d.get("mach:category")
        if c:
            cats.add(c)
    return n, len(cats)


def _marker(name: str) -> re.Pattern:
    return re.compile(rf"<!-- {name} -->(.*?)<!-- /{name} -->", re.DOTALL)


def _read_marker(text: str, name: str) -> str | None:
    m = _marker(name).search(text)
    return m.group(1) if m else None


def _set_marker(text: str, name: str, value: str) -> str:
    return _marker(name).sub(f"<!-- {name} -->{value}<!-- /{name} -->", text)


def check(write: bool) -> int:
    entries, cats = ground_truth()
    expected = {
        "entries": str(entries),
        "categories": str(cats),
    }
    errors: list[str] = []

    # ── README markers ──
    if not README.exists():
        errors.append("README.md not found")
    else:
        text = README.read_text(encoding="utf-8")
        want = {"MACH:ENTRY_COUNT": expected["entries"], "MACH:CATEGORY_COUNT": expected["categories"]}
        changed = False
        for marker, value in want.items():
            got = _read_marker(text, marker)
            if got is None:
                errors.append(f"README.md: missing marker {marker} (add it to track this claim)")
            elif got != value:
                if write:
                    text = _set_marker(text, marker, value)
                    changed = True
                    print(f"README.md: {marker} {got!r} -> {value!r}")
                else:
                    errors.append(
                        f"README.md: {marker} says {got!r} but catalogue has {value!r} "
                        f"(run: python scripts/check_consistency.py --write)"
                    )
        if write and changed:
            README.write_text(text, encoding="utf-8")

    # ── index.html STAT:TOTAL (generated by generate_entries.py; check only) ──
    if INDEX.exists():
        got = _read_marker(INDEX.read_text(encoding="utf-8"), "STAT:TOTAL")
        if got is None:
            errors.append("index.html: missing STAT:TOTAL marker")
        elif got != expected["entries"]:
            errors.append(
                f"index.html: STAT:TOTAL says {got!r} but catalogue has {expected['entries']!r} "
                f"(run: python scripts/generate_entries.py)"
            )

    if errors:
        print(f"\nCatalogue ground truth: {entries} entries, {cats} categories\n")
        for e in errors:
            print(f"ERROR: {e}")
        return 1

    print(f"Consistent: {entries} entries, {cats} categories — README and index.html agree.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true", help="rewrite README markers to match the catalogue")
    ap.add_argument("--check", action="store_true", help="verify only (default)")
    args = ap.parse_args()
    return check(write=args.write)


if __name__ == "__main__":
    raise SystemExit(main())
